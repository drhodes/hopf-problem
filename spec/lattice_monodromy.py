class LatticeBasisReq(LatticeMonodromyProof):
    r"""
    In Section 2.1 of the paper, the lattice $V \cong \mathbb{Z}^4$ has basis $(\gamma, u, w, \delta)$,
    and its dual lattice $\Lambda = V^* = \mathrm{Hom}(V, \mathbb{Z})$ has dual basis
    $(\hat{\gamma}, \hat{u}, \hat{w}, \hat{\delta})$ with pairings $\langle \hat{\alpha}, \beta \rangle = \delta_{\alpha,\beta}$.
    The system must formalize `V` and `Lambda` as free $\mathbb{Z}$-modules of rank 4 with canonical dual pairings.
    """
    deps = []

    def lean_declaration(self):
        return "HopfProblem.Lattice.V"

    def verification_status(self):
        return "VERIFIED"


class MonodromyGeneratorsReq(LatticeMonodromyProof):
    r"""
    In Definition 2.1 and Lemma 2.2, the automorphisms $T_1, T_2 \in \mathrm{Aut}(V)$ are given by:
    $$T_1 = \begin{pmatrix} 1 & 0 & -6 & 2 \\ 0 & -1 & 1 & 1 \\ 0 & -1 & 0 & 1 \\ 0 & 0 & 0 & 1 \end{pmatrix}, \quad
      T_2 = \begin{pmatrix} 1 & 6 & 0 & -3 \\ 0 & 0 & -1 & 1 \\ 0 & 1 & 0 & 0 \\ 0 & 0 & 0 & 1 \end{pmatrix}.$$
    The system must formalize $T_1, T_2$, prove $\det(T_1) = \det(T_2) = 1$, and verify orders:
    $T_1^3 = I$ and $T_2^4 = I$.
    """
    deps = [LatticeBasisReq]

    def lean_declaration(self):
        return "HopfProblem.Lattice.T1_cube"

    def verification_status(self):
        return "VERIFIED"


class UnipotentCuspMonodromyReq(LatticeMonodromyProof):
    r"""
    In Definition 2.1 and Lemma 2.2(iii), the parabolic cusp monodromy is $T_0 := (T_1 T_2)^{-1} = I + N$,
    where the nilpotent matrix $N = T_0 - I$ satisfies:
    $$N^2 = 0, \quad N\gamma = 0, \quad Nu = 0, \quad Nw = -u, \quad N\delta = \gamma.$$
    The system must formalize $T_0$ and $N$, proving $N^2 = 0$ and Jordan rank 2.
    """
    deps = [MonodromyGeneratorsReq]

    def lean_declaration(self):
        return "HopfProblem.Lattice.T0_unipotent"

    def verification_status(self):
        return "VERIFIED"


