class ToricSublatticeReq(LatticeMonodromyProof):
    r"""
    In Definition 2.5 and Lemma 2.6, the toric vanishing sublattice is:
    $$\Lambda_{\mathrm{tor}} := \ker(M_0 - I) = \mathrm{im}(M_0 - I) = \langle \hat{w}, \hat{\delta} \rangle \subset \Lambda,$$
    and the quotient $\bar{\Lambda} := \Lambda / \Lambda_{\mathrm{tor}} \cong \mathbb{Z}^2$ has basis $(\bar{\hat{\gamma}}, \bar{\hat{u}})$.
    The operator $M_0 - I$ induces a unimodular $\mathbb{Z}$-linear isomorphism:
    $$B_0 : \bar{\Lambda} \xrightarrow{\sim} \Lambda_{\mathrm{tor}}, \quad \bar{\hat{\gamma}} \mapsto -\hat{\delta}, \quad \bar{\hat{u}} \mapsto \hat{w}.$$
    The system must formalize $\Lambda_{\mathrm{tor}}$, $\bar{\Lambda}$, and the isomorphism $B_0$.
    """
    deps = [UnipotentCuspMonodromyReq, DualMonodromyMatricesReq]

    def lean_declaration(self):
        return "HopfProblem.Lattice.LambdaTor"

    def verification_status(self):
        return "VERIFIED"


class MonodromyInvariantsReq(LatticeMonodromyProof):
    r"""
    In Lemma 2.7, under the group $G = \langle T_1, T_2 \rangle$:
    1. The invariant submodule $V^G = \mathbb{Q}\gamma \cap V = \mathbb{Z}\gamma$ is of rank 1.
    2. The coinvariant quotient of $\Lambda$ is $\Lambda / \ker\gamma \cong \mathbb{Z}$, detected by $\gamma$ alone.
    3. The vector $\varepsilon := \hat{\gamma} + 2\hat{u} - 4\hat{w}$ is fixed by $A_1$.
    4. The vector $\varepsilon' := \hat{\gamma} + 3\hat{u} - 3\hat{w}$ is fixed by $A_2$.
    The system must formalize and machine-check these invariant vectors and coinvariant projections.
    """
